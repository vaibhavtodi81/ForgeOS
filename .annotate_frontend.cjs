// Chooses a plain-language explanation based on the line's syntax and its JSX/JavaScript context.
function explain(line, mode, file) {
  const text = line.trim()
  const tag = text.match(/^<\/?([A-Za-z][\w.-]*)/)
  const attr = text.match(/^([A-Za-z_:][\w:.-]*)\s*=/)

  if (mode === 'tag' && attr) {
    const name = attr[1]
    if (name === 'className') return 'Applies utility classes so the element’s layout, spacing, and appearance match the design.'
    if (name.startsWith('aria-')) return `Provides ${name} accessibility information so assistive technology can describe the element.`
    if (name.startsWith('on')) return `Connects the ${name.slice(2) || 'user'} event to its handler so the interface can respond to interaction.`
    if (name === 'type') return 'Chooses the element’s browser behavior, such as a button action or input format.'
    if (name === 'value' || name === 'defaultValue') return 'Supplies the value shown by this form control so the user sees the current data.'
    if (name === 'disabled') return 'Controls whether the element can be used, preventing actions that are not currently available.'
    if (name === 'href' || name === 'to') return 'Sets the destination so activating this link or route control opens the intended screen.'
    if (name === 'src') return 'Selects the image or other resource displayed by this element.'
    if (name === 'id') return 'Gives the element a stable identifier for linking, lookup, or styling.'
    if (name === 'role') return 'Declares the accessibility role so assistive technology can interpret the element’s purpose.'
    if (name === 'key') return 'Gives this rendered item a stable identity so React can update lists efficiently.'
    return `Sets the ${name} property so this element receives the data or behavior required by this screen.`
  }

  if (mode === 'jsx' && tag) {
    const closing = text.startsWith('</')
    const name = tag[1]
    const reason =
      name === 'button' ? 'to provide an action the user can activate' :
      name === 'form' ? 'to group controls that submit related information' :
      name === 'main' ? 'to identify the page’s primary content' :
      name === 'section' ? 'to group related content into a meaningful region' :
      name === 'label' ? 'to name a form control for users and assistive technology' :
      ['input', 'select', 'textarea'].includes(name) ? 'to collect or display a value' :
      name === 'img' ? 'to display visual content' :
      name === 'a' ? 'to provide navigation to another location' :
      'to organize this part of the interface'
    return closing
      ? `Closes the <${name}> element so later content is no longer part of this region.`
      : `Starts the <${name}> element ${reason}.`
  }
  if (mode === 'jsx') return 'Adds this JSX content to the surrounding interface so related information or controls appear in the right place.'

  let match = text.match(/^import\s+(.+?)\s+from\s+['"]([^'"]+)['"]/)
  if (match) return `Imports ${match[1].replace(/[{}]/g, '').trim()} from ${match[2]} so this module can reuse that component, helper, or library.`
  match = text.match(/^(?:export\s+)?(?:async\s+)?function\s+([\w$]+)/)
  if (match) return `Defines ${match[1]} so this module can perform its named task when needed.`
  match = text.match(/^(?:export\s+)?(?:const|let|var)\s+([\w$]+)/)
  if (match) {
    const name = match[1]
    if (/useState\s*\(/.test(text)) return `Creates ${name} as React state so the component remembers changing interface data between renders.`
    if (/useEffect\s*\(/.test(text)) return `Defines ${name} as an effect so the component can synchronize with browser or external behavior.`
    if (/useMemo\s*\(/.test(text)) return `Caches ${name} so its calculation is repeated only when its inputs change.`
    return `Stores the value in ${name} so later lines can reuse this data or behavior for the current feature.`
  }
  match = text.match(/^export\s+default\s+([\w$]+)/)
  if (match) return `Exports ${match[1]} as this file’s default value so other modules can load the main feature.`
  if (/^return\b/.test(text)) return 'Returns the result so the caller or React receives the value or interface this function provides.'
  if (/^if\s*\(/.test(text)) return 'Checks this condition before continuing so the code can choose the correct path for the current state.'
  if (/^else\b/.test(text)) return 'Handles the alternative branch when the preceding condition was not met.'
  if (/\bawait\b/.test(text)) return 'Waits for the asynchronous result before using it, so later work receives completed data.'
  if (/^try\b/.test(text)) return 'Starts an error-handling region so failures can be caught and handled safely.'
  if (/^catch\b/.test(text)) return 'Handles an error from the preceding operation so the interface can recover or show feedback.'
  if (/\.map\s*\(/.test(text)) return 'Transforms each collection item so the corresponding values or interface elements can be produced.'
  if (/\.filter\s*\(/.test(text)) return 'Keeps only items matching this condition so the result contains relevant data.'
  if (/^throw\b/.test(text)) return 'Stops the current operation with an error so the calling code can handle the failure.'
  if (/^\}\s*[,;]?\s*$/.test(text)) return 'Closes the current block or object so the grouped statements or settings end here.'
  if (/^\{\s*$/.test(text)) return 'Opens a block or object so its related statements or settings can be grouped together.'
  if (/^\)\s*[,;]?\s*$/.test(text)) return 'Closes this function call or grouped expression so the surrounding code can continue.'
  if (/^\(\s*$/.test(text)) return 'Opens an argument list or grouped expression so its related values are passed together.'
  match = text.match(/^([A-Za-z_$][\w$]*)\s*:/)
  if (match) return `Sets the ${match[1]} field so the surrounding object or component receives this setting.`
  if (/^\w/.test(text) && /\(/.test(text)) return 'Calls this helper or component so the feature can perform the operation or render the control represented here.'
  return `Continues the ${file.endsWith('.config.ts') ? 'configuration' : 'component or data'} expression so its related values and behavior stay grouped together.`
}

// Processes each source file independently so Babel can identify valid token and JSX boundaries.
for (const file of files) {
  const source = fs.readFileSync(file, 'utf8')
  // Enables both TypeScript and JSX parsing, which are used together in TSX files.
  const ast = parser.parse(source, {
    sourceType: 'unambiguous',
    plugins: ['typescript', 'jsx', 'decorators-legacy'],
    tokens: true,
  })
  // Keeps line endings intact so token line numbers still match the source being rewritten.
  const lines = source.split(/(?<=\n)/)
  // Maps each parser token back to its source line for tracking nested JSX syntax.
  const tokenLines = new Map()
  // Avoids inserting comments inside multiline template strings, where comments would become displayed text.
  const templateLines = new Set()
  for (const token of ast.tokens) {
    const label = token.type?.label ?? ''
    if (!label || label === 'eof') continue
    for (let number = token.loc.start.line; number <= token.loc.end.line; number++) {
      if (!tokenLines.has(number)) tokenLines.set(number, [])
      tokenLines.get(number).push(token)
    }
    if (label.startsWith('template') && token.loc.end.line > token.loc.start.line) {
      for (let number = token.loc.start.line; number <= token.loc.end.line; number++) templateLines.add(number)
    }
  }

  // Tracks whether the current line belongs to JSX, a tag's attributes, or ordinary JavaScript.
  let jsxDepth = 0
  let inTag = false
  let expressionDepth = 0
  const expressionBaselines = []
  const elementParents = []
  const tagFrames = []
  const output = []

  // Walks line by line so each generated explanation can be placed immediately before its source line.
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]
    const number = index + 1
    const trimmed = line.trim()
    const inExpressionJs = expressionDepth > 0 && jsxDepth <= (expressionBaselines.at(-1) ?? 0)
    const mode = inTag ? 'tag' : jsxDepth > 0 && !inExpressionJs ? 'jsx' : 'js'

    // Leaves blank lines, existing comments, and template-string content untouched.
    if (
      trimmed &&
      !/^(?:\/\/|\/\*|\*|\{\/\*|\*\/)/.test(trimmed) &&
      !templateLines.has(number)
    ) {
      const indent = line.match(/^\s*/)[0]
      const comment = explain(line, mode, file)
      output.push(
        mode === 'tag' ? `${indent}/* ${comment} */\n` :
        mode === 'jsx' ? `${indent}{/* ${comment} */}\n` :
        `${indent}// ${comment}\n`,
      )
    }
    // Retains the original source line after adding any applicable explanation.
    output.push(line)

    // Updates the JSX state from parser tokens so the next line receives a syntactically valid comment.
    for (const token of tokenLines.get(number) ?? []) {
      const label = token.type?.label ?? ''
      if (label === 'jsxTagStart') {
        // Opening and closing tags both start with this token; the following character distinguishes them.
        const after = source.slice(token.end, token.end + 1)
        tagFrames.push({ parentTag: inTag, closing: after === '/' })
        inTag = true
      } else if (label === 'jsxTagEnd' && inTag) {
        const frame = tagFrames.pop()
        // Self-closing tags do not increase JSX nesting; regular tags do.
        const selfClosing = source.slice(token.start - 1, token.start) === '/'
        if (frame.closing) {
          jsxDepth = Math.max(0, jsxDepth - 1)
          inTag = elementParents.pop() ?? frame.parentTag
        } else if (selfClosing) {
          inTag = frame.parentTag
        } else {
          elementParents.push(frame.parentTag)
          jsxDepth++
          inTag = false
        }
      } else if (label === '{') {
        // JSX braces open JavaScript expressions, so later comments must switch to JavaScript syntax there.
        if (expressionDepth === 0 && (inTag || jsxDepth > 0)) expressionBaselines.push(jsxDepth)
        if (expressionDepth > 0 || inTag || jsxDepth > 0) expressionDepth++
      } else if (label === '}' && expressionDepth > 0) {
        // Returning to JSX after the matching brace restores the surrounding JSX nesting level.
        expressionDepth--
        if (expressionDepth === 0) expressionBaselines.pop()
      }
    }
  }
  // Writes the annotated version only after the entire file has been analyzed.
  fs.writeFileSync(file, output.join(''))
}

// Adds HTML explanations using HTML comments rather than the JavaScript/JSX comment forms above.
const html = fs.readFileSync(htmlPath, 'utf8')
fs.writeFileSync(
  htmlPath,
  html.split(/(?<=\n)/).map((line) => {
    const text = line.trim()
    if (!text || /^<!--/.test(text)) return line
    const indent = line.match(/^\s*/)[0]
    const explanation =
      text.startsWith('<!doctype') ? 'Declares an HTML5 document so browsers use modern, standards-based rendering.' :
      text.startsWith('<html') ? 'Starts the document root and declares the language used by its text.' :
      text.startsWith('<head') ? 'Begins metadata that configures the page before its visible content.' :
      text.startsWith('<meta charset') ? 'Sets UTF-8 so the page can safely display a wide range of characters.' :
      text.startsWith('<link') ? 'Loads the site icon so browser tabs can identify this application.' :
      text.startsWith('<meta name="viewport') ? 'Scales the page to the device width so the interface works on mobile screens.' :
      text.startsWith('<title') ? 'Sets the text shown in the browser tab for this page.' :
      text.startsWith('<body') ? 'Begins the document body where the application interface is mounted.' :
      text.includes('id="root"') ? 'Creates the DOM mount point where React renders the application.' :
      text.startsWith('<script') ? 'Loads the frontend entry module that starts the React application.' :
      text.startsWith('</') ? 'Closes the current HTML section so following content has the correct document structure.' :
      'Groups document content in the correct browser-rendered section.'
    return `${indent}<!-- ${explanation} -->\n${line}`
  }).join(''),
)

// Adds one explanatory ignore comment above each active pattern while retaining existing comments.
fs.writeFileSync(
  ignorePath,
  fs.readFileSync(ignorePath, 'utf8').split(/(?<=\n)/).map((line) => {
    const text = line.trim()
    if (!text || text.startsWith('#')) return line
    const explanation =
      /log|\.log/.test(text) ? 'Ignores generated logs so machine-specific output does not clutter version history.' :
      text === 'node_modules' ? 'Keeps installed third-party packages out of Git because package manifests can recreate them.' :
      /^dist/.test(text) ? 'Excludes generated build output because it can be recreated from source.' :
      /local/.test(text) ? 'Leaves local-only settings out of shared commits.' :
      'Ignores local editor or operating-system metadata rather than application source.'
    return `# ${explanation}\n${line}`
  }).join(''),
)

// Reads the cleaned environment example and adds a single note for the frontend API endpoint.
