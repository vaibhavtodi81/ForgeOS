if (!env.includes('# Provides the local backend endpoint')) {
  fs.writeFileSync(
    envPath,
    env.replace(
      /^(VITE_API_BASE_URL=.*)$/m,
      '# Provides the local backend endpoint the frontend uses when sending API requests.\n$1',
    ),
  )
}

